def label(lang: str, feature_id: str, ru_label: str) -> tuple[str, bool]:
    """Подпись признака на языке ответа и флаг «переведено». graph.requisite.phone → graph.requisite."""
    if lang != "kk":
        return ru_label, True
    key = "graph.requisite" if feature_id.startswith("graph.requisite.") else feature_id
    kk = LABELS_KK.get(key)
    return (kk, True) if kk else (ru_label, False)


def say(lang: str, key: str, **values: object) -> str:
    entry = TEXT[key]
    return entry.get(lang, entry["ru"]).format(**values)


def reply_lang(text: str, user_lang: str | None) -> str:
    """Язык ответа: казахский, если пост на казахском; без текста или на команду — по языку Telegram."""
    if (text or "").startswith("/"):
        text = ""
    if len(KK_LETTERS.findall(text or "")) >= MIN_KK_LETTERS:
        return "kk"
    if not (text or "").strip() and (user_lang or "").lower().startswith("kk"):
        return "kk"
    return "ru"
