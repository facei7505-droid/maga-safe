@dataclass(frozen=True)
class Feature:
    id: str
    track: str  # lottery | casino | pyramid | common
    label: str
    weight: float
    patterns: tuple[str, ...]
    stop: bool = False  # стоп-признак легальности или антиреклама
    core: bool = False  # «ядровой» признак, нужен для высокого риска трека

    def compiled(self) -> tuple[re.Pattern[str], ...]:
        # Латинская i сворачивается в казахскую «і», поэтому «и» и «і» в шаблонах взаимозаменяемы.
        return tuple(re.compile(re.sub("[иі]", "[иі]", p), re.IGNORECASE) for p in self.patterns)


def w(*stems: str) -> str:
    """Слово, начинающееся с одной из основ."""
    return r"(?<!\w)(?:" + "|".join(stems) + r")\w*"


def near(left: str, right: str, gap: int = 40) -> str:
    """Два шаблона в одном предложении на расстоянии до gap символов, в любом порядке."""
    return rf"(?:{left})[^.!?\n]{{0,{gap}}}?(?:{right})|(?:{right})[^.!?\n]{{0,{gap}}}?(?:{left})"


