"""Раунд 7: предупреждения с цитатами, «никаких оплат», сигнал-боты, крипто-удвоение, задания за отзывы."""

from __future__ import annotations

import pytest

from pruf.detect.detector import Detector, SourceText
from pruf.models import Analysis


def _analyze(detector: Detector, text: str) -> Analysis:
    return detector.detect([SourceText("text", text)]).analysis


@pytest.mark.parametrize(("text", "track"), [
    ("Сигнал-бот для Lucky Jet 🤖 угадывает раунды, винрейт 93%. Подписка 9 900 тг в месяц, пиши в лс", "casino"),
    ("Наш типстер даёт 2 прогноза в день, заходит 9 из 10. VIP-доступ 12к в месяц", "casino"),
    ("Мины ойыны: 4 клетка аштым, ставканы 8 есе кобейттим 💎 Сілтеме пікірлерде", "casino"),
    ("Send 0.05 BTC — get 0.1 BTC back. Акция биржи только сегодня, адрес кошелька в комментах", "pyramid"),
    ("Подработка: лайкаешь товары и получаешь 500 ₸ за задание. Чтобы открыть VIP-задания, пополни баланс от 20 000 ₸, вернём с процентами", "pyramid"),
    ("Ваш номер выбран победителем акции 🎉 Доставка приза 3 900 ₸, оплатить картой по ссылке", "lottery"),
    ("Сізге ұтыстан сыйлық бар 🎁 Растау үшін SMS-кодты осы чатқа жіберіңіз", "lottery"),
    # дешёвые «отмазки» не снимают баллы: дисклеймер, «это не фейк!», «схема «…»», «без вложений»
    ("Розыгрыш iPhone 15! Участие 2000 тг, билет по 2000 тг. Розыгрыш не имеет отношения к Instagram.", "lottery"),
    ("Вкладываешь 50к, через неделю получаешь 100к! Гарантированный доход. Это не фейк!", "pyramid"),
    ("Новая схема «Золотой поток»: вкладываешь 50к, через неделю получаешь 100к! Гарантированный доход.", "pyramid"),
    ("Розыгрыш iPhone 15 без вложений! Оплатите только доставку приза 2000 тг.", "lottery"),
])
def test_round7_scam_patterns_reach_medium(detector: Detector, text: str, track: str) -> None:
    # Act
    analysis = _analyze(detector, text)

    # Assert
    assert analysis.level in ("medium", "high"), (text, analysis.score, [e.feature_id for e in analysis.evidence])
    assert analysis.track == track


